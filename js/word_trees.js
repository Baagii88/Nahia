const WordTree = {id:'person',branch:null};
function treeGloss(text) { return WORD_TREE_GLOSSES.find(w=>w.text===text); }
function treeDefinition() { return WORD_TREES.find(t=>t.id===WordTree.id)||WORD_TREES[0]; }
function treeReadingKey(text) { return text.normalize('NFC').toLowerCase().replace(/[\s·'’]/g,''); }
function treeCanonical(text) {
  const g=treeGloss(text);
  return getAllWordsPool().find(w=>w.simplified===text && treeReadingKey(w.pinyin||'')===treeReadingKey(g?.pinyin||''));
}
function treeCardWord(text) { return treeCanonical(text)||window.MONGOL_HSK_SUPPLEMENTAL.find(w=>w.simplified===text); }
function chooseWordTree(id) { if(!WORD_TREES.some(t=>t.id===id))return; WordTree.id=id;WordTree.branch=null;renderLearn(); }
function toggleWordBranch(index) { if(!treeDefinition().branches[index])return;WordTree.branch=WordTree.branch===index?null:index;renderLearn(); }
function treeActions(text) {
  const ref=WORD_TREE_GLOSSES.findIndex(w=>w.text===text), canonical=treeCanonical(text), card=treeCardWord(text);
  return `<div class="word-tree-actions">${learnButton('🔊 Сонсох',`treeAction('listen',${ref})`)}${learnButton('✍ Бичих',`treeAction('write',${ref})`)}${learnButton(AppState.srsCards.some(w=>w.id===card.id)?'Картнаас хасах':'Картдаа нэмэх',`treeAction('srs',${ref})`)}</div><small>${canonical?'Шинэ HSK '+String(canonical.level).replace('_','–'):'Нэмэлт сурах үг'}</small>`;
}
function treeAction(action,index) {
  const word=WORD_TREE_GLOSSES[index];if(!word)return;
  if(action==='listen')speakText(word.text);
  else if(action==='write')learnWrite(word.text);
  else if(action==='srs'){const match=treeCardWord(word.text);if(match){toggleSRSWord(match.id);renderLearn();}}
}
function treeCard(text,stage,mark='') {
  const g=treeGloss(text);
  return `<article class="word-tree-card stage-${stage}"><h3 lang="zh">${[...g.text].map(c=>c===mark?`<span class="word-tree-shared">${c}</span>`:c).join('')}</h3><p class="word-tree-pinyin">${escapeHtml(g.pinyin)}</p><p><strong>${escapeHtml(g.mn)}</strong></p><p lang="en">${escapeHtml(g.en)}</p>${treeActions(text)}</article>`;
}
